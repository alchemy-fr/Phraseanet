namespace Alchemy\Phrasea\Core\Provider;

use Alchemy\Phrasea\Metadata\TagFactory;
use PHPExiftool\Exiftool;
use PHPExiftool\InformationDumper;
use PHPExiftool\PHPExiftool;
use PHPExiftool\PreviewExtractor;
use PHPExiftool\RDFParser;
use PHPExiftool\Reader;
use PHPExiftool\Writer;
use Pimple\Container;
use Pimple\ServiceProviderInterface;
use Psr\Log\NullLogger;

class PHPExiftoolServiceProvider implements ServiceProviderInterface
{
    public function register(Container $app)
    {
        $app['exiftool.logger'] = function (Container $app) {
            return isset($app['monolog']) ? $app['monolog'] : new NullLogger();
        };

        /**
         * Path to the exiftool binary, null to use the one bundled with phpexiftool (vendor/exiftool/exiftool)
         */
        $app['exiftool.binary'] = function (Container $app) {
            return isset($app['conf']) ? ($app['conf']->get(['main', 'binaries', 'exiftool_binary']) ?: null) : null;
        };

        $app['exiftool.timeout'] = function (Container $app) {
            return isset($app['conf']) ? (int) $app['conf']->get(['main', 'binaries', 'exiftool_timeout'], 60) : 60;
        };

        /**
         * Directory of the tag group classes generated by phpexiftool, shared with media-alchemyst.
         * Classes are generated on first use, which takes a while.
         */
        $app['exiftool.classes-directory'] = function (Container $app) {
            $directory = $app['cache.path'] . '/exiftool';

            if (!is_dir($directory) && !@mkdir($directory, 0777, true) && !is_dir($directory)) {
                throw new \RuntimeException(sprintf('Unable to create phpexiftool classes directory %s', $directory));
            }

            $phpExiftool = new PHPExiftool($directory, $app['exiftool.logger']);

            if (!$phpExiftool->isClassesGenerated()) {
                // concurrent processes must not generate the classes at the same time
                $lock = fopen($directory . '/.generate.lock', 'c');
                if (false === $lock) {
                    throw new \RuntimeException(sprintf('Unable to lock phpexiftool classes directory %s', $directory));
                }

                try {
                    flock($lock, LOCK_EX);
                    if (!$phpExiftool->isClassesGenerated()) {
                        $phpExiftool->generateClasses([InformationDumper::LISTOPTION_MWG], ['en']);
                    }
                } finally {
                    flock($lock, LOCK_UN);
                    fclose($lock);
                }
            }

            return $phpExiftool->getClassesRootDirectory();
        };

        $app['exiftool.exiftool'] = function (Container $app) {
            return new Exiftool($app['exiftool.logger'], $app['exiftool.binary']);
        };

        $app['exiftool.rdf-parser'] = $app->factory(function (Container $app) {
            return new RDFParser($app['exiftool.classes-directory'], $app['exiftool.logger']);
        });

        $app['exiftool.reader'] = function (Container $app) {
            return Reader::create($app['exiftool.exiftool'], $app['exiftool.rdf-parser'])
                ->setTimeout($app['exiftool.timeout']);
        };

        $app['exiftool.writer'] = function (Container $app) {
            return Writer::create($app['exiftool.exiftool'])
                ->setTimeout($app['exiftool.timeout']);
        };

        $app['exiftool.preview-extractor'] = function (Container $app) {
            return new PreviewExtractor($app['exiftool.exiftool']);
        };

        TagFactory::setClassesDirectory(function () use ($app) {
            return $app['exiftool.classes-directory'];
        });
    }
}
